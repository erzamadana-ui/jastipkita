function write(file, content) {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content);
  console.log('  wrote', path.relative(REPO, file));
}

const report = contrastReport();
if (!args.has('--check')) {
  write(path.join(PKG, 'dist', 'tokens.css'), emitCss());
  write(path.join(PKG, 'dist', 'tokens.ts'), emitTs());
  write(path.join(PKG, 'dist', 'tokens.resolved.json'), JSON.stringify(JSON.parse(emitTs().split('export const tokens = ')[1].split(' as const;')[0]), null, 2) + '\n');
  write(DART_OUT, emitDart());
}
write(path.join(PKG, 'CONTRAST.md'), report.md + '\n');
// Keep the UI design-system doc in sync (content between the CONTRAST-REPORT markers).
const DOC = path.join(REPO, 'docs', '05-ui-design-system.md');
try {
  const doc = readFileSync(DOC, 'utf8');
  const START = '<!-- CONTRAST-REPORT:START -->';
  const END = '<!-- CONTRAST-REPORT:END -->';
  if (doc.includes(START) && doc.includes(END)) {
    const body = report.md
      .split('\n')
      .filter((l) => !l.startsWith('<!--') && !l.startsWith('# '))
      .map((l) => (l.startsWith('## ') ? '#' + l : l))
      .join('\n')
      .trim();
    const next = doc.slice(0, doc.indexOf(START) + START.length) + '\n' + body + '\n' + doc.slice(doc.indexOf(END));
    if (next !== doc) write(DOC, next);
  }
} catch {
  /* doc optional */
}
