const kebab = (s) => s.replace(/_/g, '-').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const cssColor = (c) => (c.a >= 1 ? c.hex : `rgba(${c.r}, ${c.g}, ${c.b}, ${+c.a.toFixed(3)})`);
const shadowCss = (layers) =>
  layers.length ? layers.map((l) => `${l.x}px ${l.y}px ${l.blur}px ${l.spread}px ${cssColor(l.color)}`).join(', ') : 'none';

