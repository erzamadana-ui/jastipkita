const P = T.color.primitive;
function primitiveHex(ref) {
  const [fam, step] = ref.split('.');
  const v = step === undefined ? P[fam] : P[fam]?.[step];
  if (typeof v !== 'string') throw new Error(`Unknown colour reference "${ref}"`);
  return v;
}
function hexToRgb(hex) {
  const n = parseInt(hex.slice(1), 16);
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 };
}
/** → { r, g, b, a, hex, ref } */
function resolveColor(v) {
  if (typeof v === 'string') {
    const m = v.match(/^\{(.+)\}$/);
    const hex = m ? primitiveHex(m[1]) : v;
    return { ...hexToRgb(hex), a: 1, hex: hex.toUpperCase(), ref: m ? m[1] : null };
  }
  if (v && v.$ref) {
    const hex = primitiveHex(v.$ref);
    return { ...hexToRgb(hex), a: v.alpha ?? 1, hex: hex.toUpperCase(), ref: v.$ref };
  }
  throw new Error(`Bad colour value ${JSON.stringify(v)}`);
}
const mapObj = (o, f) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, f(v, k)]));
const resolveTones = (group) => mapObj(group, (tones) => mapObj(tones, (tone) => mapObj(tone, resolveColor)));

