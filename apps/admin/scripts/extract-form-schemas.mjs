// Extracts the JSON Schemas that drive generated admin forms (promotion conditions/benefit, rule versions,
// settlement change) from docs/api/openapi.json into src/api/form-schemas.json ($refs inlined).
// Run via `pnpm gen:api` together with openapi-typescript so forms and types never drift from the contract.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(readFileSync(resolve(here, '../../../docs/api/openapi.json'), 'utf8'));
const NAMES = [
  'AdminPromoConditions',
  'AdminPromoBenefit',
  'AdminPromotionCreate',
  'AdminCustomsRuleCreate',
  'AdminRestrictedItemCreate',
  'AdminRulePreview',
  'AdminSettlementChangeRequest',
  'AdminTrustOverrideRequest',
  'AdminMigrationWorkflowStart',
];

function inline(node, depth = 0) {
  if (depth > 20) throw new Error('schema too deep');
  if (Array.isArray(node)) return node.map((n) => inline(n, depth + 1));
  if (!node || typeof node !== 'object') return node;
  if (node.$ref) {
    const name = node.$ref.split('/').pop();
    return inline(spec.components.schemas[name], depth + 1);
  }
  return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, inline(v, depth + 1)]));
}

const out = { $comment: 'GENERATED by scripts/extract-form-schemas.mjs from docs/api/openapi.json — do not edit.', schemas: {} };
for (const n of NAMES) {
  if (!spec.components.schemas[n]) throw new Error(`missing schema ${n}`);
  out.schemas[n] = inline(spec.components.schemas[n]);
}
writeFileSync(resolve(here, '../src/api/form-schemas.json'), `${JSON.stringify(out, null, 2)}\n`);
console.log(`form schemas: ${NAMES.length} → src/api/form-schemas.json`);
